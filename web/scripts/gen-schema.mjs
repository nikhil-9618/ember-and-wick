#!/usr/bin/env node
/**
 * Bundles migrations/*.sql into src/lib/schema.generated.ts so the Worker can
 * bootstrap an empty database when BOOTSTRAP_DB=1.
 *
 * Run after adding a migration: `node scripts/gen-schema.mjs`
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const migrationsDir = join(root, "migrations");

const files = readdirSync(migrationsDir)
  .filter((file) => file.endsWith(".sql"))
  .sort();

// D1's multi-statement exec treats a leading comment-only chunk as an empty
// statement, so comment lines are removed from the bundled copy.
const stripComments = (text) =>
  text
    .split("\n")
    .filter((line) => !line.trim().startsWith("--"))
    .join("\n")
    .trim();

const sql = files.map((file) => stripComments(readFileSync(join(migrationsDir, file), "utf8"))).join("\n\n");

const output = `// AUTO-GENERATED by scripts/gen-schema.mjs — do not edit by hand.
// Source: migrations/${files.join(", migrations/")}
export const SCHEMA_SQL = ${JSON.stringify(sql)};
export const SCHEMA_VERSION = ${JSON.stringify(files[files.length - 1]?.replace(/\.sql$/, "") ?? "none")};
`;

writeFileSync(join(root, "src", "lib", "schema.generated.ts"), output, "utf8");
console.log(`Wrote schema.generated.ts from ${files.length} migration(s) (${sql.length} bytes).`);
